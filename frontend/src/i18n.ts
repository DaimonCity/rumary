export const I18nContext = createContext<{
    locale: Locale;
    setLocale: (locale: Locale) => void;
    t: (value: string) => string
}>({
    locale: 'ru', setLocale: () => undefined, t: value => value
});

export const useI18n = () => useContext(I18nContext);
export const translate = (locale: Locale, key: keyof Dictionary) => {
    const direct = dictionaries[locale][key] ?? dictionaries.en[key];
    if (direct) return direct;

    const separator = key.indexOf(':');
    if (separator === -1) return key;
    const baseKey = key.slice(0, separator);
    const detail = key.slice(separator + 1);
    const base = dictionaries[locale][baseKey] ?? dictionaries.en[baseKey];
    return base ? `${base}: ${detail}` : key;
};
